"""Application enums shared by models and future services."""

from enum import StrEnum


class UserRole(StrEnum):
    ADMINISTRATOR = "ADMINISTRATOR"
    USER = "USER"


class UserStatus(StrEnum):
    ACTIVE = "ACTIVE"
    DISABLED = "DISABLED"


class PermissionLevel(StrEnum):
    READ = "READ"
    EDIT = "EDIT"


class DocumentAccessLevel(StrEnum):
    """Effective access resolved for a user on a specific document."""

    OWNER = "OWNER"
    EDIT = "EDIT"
    READ = "READ"
    ADMINISTRATOR = "ADMINISTRATOR"


class AuditOutcome(StrEnum):
    SUCCESS = "SUCCESS"
    DENIED = "DENIED"
    FAILURE = "FAILURE"


class AuditAction(StrEnum):
    """Known audit actions. The database column stays extensible for later phases."""

    USER_REGISTERED = "USER_REGISTERED"
    USER_STATUS_CHANGED = "USER_STATUS_CHANGED"
    USER_ROLE_CHANGED = "USER_ROLE_CHANGED"
    LOGIN_SUCCESS = "LOGIN_SUCCESS"
    LOGIN_FAILURE = "LOGIN_FAILURE"
    LOGOUT = "LOGOUT"
    DOCUMENT_UPLOAD = "DOCUMENT_UPLOAD"
    DOCUMENT_METADATA_UPDATE = "DOCUMENT_METADATA_UPDATE"
    DOCUMENT_DOWNLOAD = "DOCUMENT_DOWNLOAD"
    DOCUMENT_DELETE = "DOCUMENT_DELETE"
    PERMISSION_GRANT = "PERMISSION_GRANT"
    PERMISSION_UPDATE = "PERMISSION_UPDATE"
    PERMISSION_REVOKE = "PERMISSION_REVOKE"
    DOCUMENT_ACCESS_DENIED = "DOCUMENT_ACCESS_DENIED"
    DOCUMENT_UPLOAD_DENIED = "DOCUMENT_UPLOAD_DENIED"
    DOCUMENT_DOWNLOAD_DENIED = "DOCUMENT_DOWNLOAD_DENIED"
    DOCUMENT_EDIT_DENIED = "DOCUMENT_EDIT_DENIED"
    DOCUMENT_DELETE_DENIED = "DOCUMENT_DELETE_DENIED"
    PERMISSION_CHANGE_DENIED = "PERMISSION_CHANGE_DENIED"
    AUDIT_ACCESS_DENIED = "AUDIT_ACCESS_DENIED"
