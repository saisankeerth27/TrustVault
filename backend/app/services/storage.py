"""Private Supabase Storage integration.

The application never stores or returns public object URLs. Object keys are
generated by the backend, and server-side credentials never reach the browser.
"""

from __future__ import annotations

import logging
from functools import lru_cache
from io import BytesIO
from typing import IO
from urllib.parse import quote

import httpx

from app.core.config import Settings, get_settings

logger = logging.getLogger(__name__)


class StorageConfigurationError(Exception):
    """Raised when required Supabase Storage settings are missing or unsafe."""


class StorageOperationError(Exception):
    """Raised when Supabase Storage cannot complete an operation."""


class StorageObjectNotFoundError(StorageOperationError):
    """Raised when a requested private object does not exist."""


def _is_missing_object(response: httpx.Response) -> bool:
    if response.status_code == 404:
        return True
    if response.status_code != 400:
        return False
    try:
        payload = response.json()
    except ValueError:
        return False
    if not isinstance(payload, dict):
        return False
    return str(payload.get("statusCode")) == "404" or payload.get("code") in {
        "NoSuchKey",
        "NoSuchObject",
    }


class SupabaseStorage:
    def __init__(self, settings: Settings) -> None:
        self._settings = settings
        self._client: httpx.Client | None = None

    def _configuration(self) -> tuple[str, str, str]:
        settings = self._settings
        missing = [
            name
            for name in (
                "SUPABASE_URL",
                "SUPABASE_STORAGE_BUCKET",
                "SUPABASE_SERVICE_ROLE_KEY",
            )
            if not getattr(settings, name.lower())
        ]
        if missing:
            logger.error(
                "Supabase Storage configuration is incomplete: %s",
                ", ".join(missing),
            )
            raise StorageConfigurationError("Supabase Storage is not configured.")

        url = settings.supabase_url
        bucket = settings.supabase_storage_bucket
        service_role_key = settings.supabase_service_role_key

        if url is None or not url.startswith("https://"):
            raise StorageConfigurationError("SUPABASE_URL must use HTTPS.")
        if bucket is None or service_role_key is None:
            raise StorageConfigurationError("Supabase Storage is not configured.")

        return (url, bucket, service_role_key.get_secret_value())

    @staticmethod
    def _headers(service_role_key: str) -> dict[str, str]:
        if service_role_key.startswith("sb_"):
            return {"apikey": service_role_key}
        return {
            "apikey": service_role_key,
            "Authorization": f"Bearer {service_role_key}",
        }

    def _get_client(self) -> httpx.Client:
        if self._client is None:
            self._client = httpx.Client(
                timeout=httpx.Timeout(30.0, connect=5.0),
                follow_redirects=False,
            )
        return self._client

    def _object_url(self, key: str) -> str:
        url, bucket, _ = self._configuration()
        safe_bucket = quote(bucket, safe="")
        safe_key = quote(key.lstrip("/"), safe="/")
        return f"{url}/storage/v1/object/{safe_bucket}/{safe_key}"

    def _bucket_url(self) -> str:
        url, bucket, _ = self._configuration()
        return f"{url}/storage/v1/bucket/{quote(bucket, safe='')}"

    def upload_bytes(self, *, key: str, data: bytes, content_type: str) -> None:
        _, _, service_role_key = self._configuration()
        headers = self._headers(service_role_key)
        headers["Content-Type"] = content_type
        headers["x-upsert"] = "false"
        try:
            response = self._get_client().post(
                self._object_url(key),
                headers=headers,
                content=data,
            )
        except httpx.HTTPError as exc:
            logger.warning("Supabase Storage upload failed with %s.", exc.__class__.__name__)
            raise StorageOperationError("Document storage is temporarily unavailable.") from exc

        if not response.is_success:
            logger.warning("Supabase Storage upload failed with HTTP %s.", response.status_code)
            raise StorageOperationError("Document storage is temporarily unavailable.")

    def open_download(self, *, key: str) -> IO[bytes]:
        _, _, service_role_key = self._configuration()
        try:
            response = self._get_client().get(
                self._object_url(key),
                headers=self._headers(service_role_key),
            )
        except httpx.HTTPError as exc:
            logger.warning("Supabase Storage download failed with %s.", exc.__class__.__name__)
            raise StorageOperationError("Document storage is temporarily unavailable.") from exc

        if _is_missing_object(response):
            logger.warning("Supabase Storage download failed with HTTP %s.", response.status_code)
            raise StorageObjectNotFoundError("Document content is unavailable.")
        if not response.is_success:
            logger.warning("Supabase Storage download failed with HTTP %s.", response.status_code)
            raise StorageOperationError("Document storage is temporarily unavailable.")

        return BytesIO(response.content)

    def delete_object(self, *, key: str) -> None:
        _, _, service_role_key = self._configuration()
        try:
            response = self._get_client().delete(
                self._object_url(key),
                headers=self._headers(service_role_key),
            )
        except httpx.HTTPError as exc:
            logger.warning("Supabase Storage delete failed with %s.", exc.__class__.__name__)
            raise StorageOperationError("Document storage cleanup failed.") from exc

        if _is_missing_object(response):
            logger.warning("Supabase Storage delete failed with HTTP %s.", response.status_code)
            raise StorageObjectNotFoundError("Document content is unavailable.")
        if not response.is_success:
            logger.warning("Supabase Storage delete failed with HTTP %s.", response.status_code)
            raise StorageOperationError("Document storage cleanup failed.")

    def get_object_metadata(self, *, key: str) -> dict[str, object]:
        _, _, service_role_key = self._configuration()
        try:
            response = self._get_client().head(
                self._object_url(key),
                headers=self._headers(service_role_key),
            )
        except httpx.HTTPError as exc:
            logger.warning(
                "Supabase Storage metadata lookup failed with %s.",
                exc.__class__.__name__,
            )
            raise StorageOperationError("Document storage is temporarily unavailable.") from exc

        if not response.is_success:
            logger.warning(
                "Supabase Storage metadata lookup failed with HTTP %s.",
                response.status_code,
            )
            raise StorageOperationError("Document storage is temporarily unavailable.")

        return {
            "size": response.headers.get("content-length"),
            "content_type": response.headers.get("content-type"),
            "etag": response.headers.get("etag"),
        }

    def check_connection(self) -> None:
        """Verify credentials, bucket access, and private bucket configuration."""

        _, _, service_role_key = self._configuration()
        try:
            response = self._get_client().get(
                self._bucket_url(),
                headers=self._headers(service_role_key),
            )
        except httpx.HTTPError as exc:
            logger.warning(
                "Supabase Storage connection check failed with %s.",
                exc.__class__.__name__,
            )
            raise StorageOperationError("Supabase Storage connection check failed.") from exc

        if not response.is_success:
            logger.warning(
                "Supabase Storage connection check failed with HTTP %s.",
                response.status_code,
            )
            raise StorageOperationError("Supabase Storage connection check failed.")

        try:
            payload = response.json()
        except ValueError as exc:
            logger.warning("Supabase Storage connection check returned invalid JSON.")
            raise StorageOperationError("Supabase Storage connection check failed.") from exc

        if isinstance(payload, dict) and payload.get("public") is True:
            logger.error("Supabase Storage bucket is public; refusing configuration.")
            raise StorageConfigurationError("Supabase Storage bucket must be private.")


@lru_cache
def get_storage_service() -> SupabaseStorage:
    return SupabaseStorage(get_settings())
