"""Private Wasabi S3 storage integration.

The application never stores or returns public object URLs. Object keys are
generated by the backend, and boto3 uses HTTPS with normal certificate
verification. Credentials are read from server-side settings only.
"""

from __future__ import annotations

import logging
from functools import lru_cache
from typing import IO

import boto3
from botocore.config import Config
from botocore.exceptions import BotoCoreError, ClientError

from app.core.config import Settings, get_settings

logger = logging.getLogger(__name__)

_MISSING_OBJECT_CODES = {"404", "NoSuchKey", "NotFound"}


class StorageConfigurationError(Exception):
    """Raised when required Wasabi settings are missing or unsafe."""


class StorageOperationError(Exception):
    """Raised when Wasabi cannot complete an operation."""


class StorageObjectNotFoundError(StorageOperationError):
    """Raised when a requested private object does not exist."""


def _safe_error_code(exc: Exception) -> str:
    if isinstance(exc, ClientError):
        code = exc.response.get("Error", {}).get("Code")
        if isinstance(code, str) and code:
            return code[:64]
        return "ClientError"
    return exc.__class__.__name__


class WasabiStorage:
    def __init__(self, settings: Settings) -> None:
        self._settings = settings
        self._client = None

    def _configuration(self) -> tuple[str, str, str, str, str]:
        settings = self._settings
        missing = [
            name
            for name in (
                "WASABI_ENDPOINT_URL",
                "WASABI_REGION",
                "WASABI_BUCKET_NAME",
                "WASABI_ACCESS_KEY_ID",
                "WASABI_SECRET_ACCESS_KEY",
            )
            if not getattr(settings, name.lower())
        ]
        if missing:
            logger.error(
                "Wasabi storage configuration is incomplete: %s",
                ", ".join(missing),
            )
            raise StorageConfigurationError("Wasabi storage is not configured.")

        endpoint = settings.wasabi_endpoint_url
        bucket = settings.wasabi_bucket_name
        access_key_id = settings.wasabi_access_key_id
        secret_access_key = settings.wasabi_secret_access_key

        if endpoint is None or not endpoint.startswith("https://"):
            raise StorageConfigurationError("Wasabi endpoint must use HTTPS.")
        if bucket is None or access_key_id is None or secret_access_key is None:
            raise StorageConfigurationError("Wasabi storage is not configured.")

        return (
            endpoint,
            settings.wasabi_region,
            bucket,
            access_key_id.get_secret_value(),
            secret_access_key.get_secret_value(),
        )

    def _get_client(self):
        if self._client is None:
            endpoint, region, _, access_key_id, secret_access_key = self._configuration()
            self._client = boto3.client(
                "s3",
                endpoint_url=endpoint,
                region_name=region,
                aws_access_key_id=access_key_id,
                aws_secret_access_key=secret_access_key,
                config=Config(
                    signature_version="s3v4",
                    s3={"addressing_style": "path"},
                    retries={"max_attempts": 2, "mode": "standard"},
                    connect_timeout=5,
                    read_timeout=30,
                ),
            )
        return self._client

    def upload_bytes(self, *, key: str, data: bytes, content_type: str) -> None:
        _, _, bucket, _, _ = self._configuration()
        try:
            self._get_client().put_object(
                Bucket=bucket,
                Key=key,
                Body=data,
                ContentType=content_type,
            )
        except (BotoCoreError, ClientError) as exc:
            logger.warning("Wasabi upload failed with code %s.", _safe_error_code(exc))
            raise StorageOperationError("Document storage is temporarily unavailable.") from exc

    def open_download(self, *, key: str) -> IO[bytes]:
        _, _, bucket, _, _ = self._configuration()
        try:
            response = self._get_client().get_object(Bucket=bucket, Key=key)
        except ClientError as exc:
            code = _safe_error_code(exc)
            logger.warning("Wasabi download failed with code %s.", code)
            if code in _MISSING_OBJECT_CODES:
                raise StorageObjectNotFoundError("Document content is unavailable.") from exc
            raise StorageOperationError("Document storage is temporarily unavailable.") from exc
        except BotoCoreError as exc:
            logger.warning("Wasabi download failed with code %s.", _safe_error_code(exc))
            raise StorageOperationError("Document storage is temporarily unavailable.") from exc

        body = response.get("Body")
        if body is None:
            logger.error("Wasabi download response did not include a body.")
            raise StorageOperationError("Document storage is temporarily unavailable.")
        return body

    def delete_object(self, *, key: str) -> None:
        _, _, bucket, _, _ = self._configuration()
        try:
            self._get_client().delete_object(Bucket=bucket, Key=key)
        except (BotoCoreError, ClientError) as exc:
            logger.warning("Wasabi delete failed with code %s.", _safe_error_code(exc))
            raise StorageOperationError("Document storage cleanup failed.") from exc

    def get_object_metadata(self, *, key: str) -> dict[str, object]:
        _, _, bucket, _, _ = self._configuration()
        try:
            response = self._get_client().head_object(Bucket=bucket, Key=key)
        except (BotoCoreError, ClientError) as exc:
            logger.warning("Wasabi metadata lookup failed with code %s.", _safe_error_code(exc))
            raise StorageOperationError("Document storage is temporarily unavailable.") from exc

        return {
            "size": response.get("ContentLength"),
            "content_type": response.get("ContentType"),
            "etag": response.get("ETag"),
        }

    def check_connection(self) -> None:
        """Verify endpoint, credentials, and bucket access without logging secrets."""

        _, _, bucket, _, _ = self._configuration()
        try:
            self._get_client().head_bucket(Bucket=bucket)
        except (BotoCoreError, ClientError) as exc:
            logger.warning("Wasabi connection check failed with code %s.", _safe_error_code(exc))
            raise StorageOperationError("Wasabi connection check failed.") from exc


@lru_cache
def get_storage_service() -> WasabiStorage:
    return WasabiStorage(get_settings())
